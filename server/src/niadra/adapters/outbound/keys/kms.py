"""Envelope encryption with the key-encryption key in AWS KMS (5.14.1).

The KEK never leaves KMS, whose HSMs are validated to FIPS 140-3 level 3, and KMS rotates it every
year. Each space's data keys come from GenerateDataKey and are stored wrapped, with the space in the
encryption context: a wrapped key of one space never opens as another's, and every unwrap is on
CloudTrail. A process asks KMS once per data key and keeps the plaintext in memory, so reads never
wait on KMS after the first.

Two more wrapped keys belong to the cell: the root of the keyed hashes (handle lookups) and the key of
the secret store, generated by KMS on the cell's first start.
"""

import asyncio
import hmac as hmac_lib
import os
from collections.abc import AsyncIterator, Callable, Mapping
from contextlib import asynccontextmanager
from dataclasses import dataclass
from typing import Any, Protocol
from uuid import UUID

from aiobotocore.config import AioConfig
from aiobotocore.session import get_session
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

from niadra.adapters.outbound.keys.local import NONCE_BYTES, derived_key
from niadra.domain.common.errors import Conflict, Unavailable

KMS_PREFIX = "kms:"
# The cell's own wrapped keys sit beside the spaces' in `data_keys`, under the nil space id.
CELL_KEYS = UUID(int=0)
HMAC_ROOT_VERSION = 1
SECRETS_ROOT_VERSION = 2
CELL_KEY_NAMES = {HMAC_ROOT_VERSION: "hmac_root", SECRETS_ROOT_VERSION: "secrets_root"}


class KmsApi(Protocol):
    """The three calls the vault makes, as the AWS SDK names them."""

    async def generate_data_key(self, **params: Any) -> dict[str, Any]: ...

    async def encrypt(self, **params: Any) -> dict[str, Any]: ...

    async def decrypt(self, **params: Any) -> dict[str, Any]: ...


class EnvelopeKeyStore(Protocol):
    """The `data_keys` table, with the id of the key that wraps each row."""

    async def load_wrapped(self, space_id: UUID) -> dict[int, tuple[bytes, str]]: ...

    async def save(self, space_id: UUID, version: int, wrapped: bytes, kek_id: str | None = None) -> None: ...

    async def destroy(self, space_id: UUID) -> list[int]: ...


@dataclass(frozen=True, slots=True)
class CellKeys:
    hmac_root: bytes
    secrets_key: bytes


def space_context(space_id: UUID) -> dict[str, str]:
    return {"niadra:space": str(space_id)}


def cell_context(version: int) -> dict[str, str]:
    return {"niadra:cell-key": CELL_KEY_NAMES[version]}


class KmsKeyVault:
    """`KeyVault` over KMS. Build it with `open`, which loads or creates the cell's keys first."""

    def __init__(
        self,
        kms: KmsApi,
        key_id: str,
        store: EnvelopeKeyStore,
        cell_keys: CellKeys,
    ) -> None:
        self._kms = kms
        self._key_id = key_id
        self._store = store
        self._hmac_root = cell_keys.hmac_root
        self._deks: dict[UUID, dict[int, bytes]] = {}
        self._kek_ids: dict[UUID, dict[int, str]] = {}
        self._destroyed: set[UUID] = set()
        self._locks: dict[UUID, asyncio.Lock] = {}
        self._space_key: Callable[[UUID], str | None] = lambda _: None

    def use_space_keys(self, space_key: Callable[[UUID], str | None]) -> None:
        """Where each space's customer-managed key comes from (the configuration's `kms_key_arn`, 10 D.1).
        A space with one gets its new data keys under it, never under the cell's key."""
        self._space_key = space_key

    @classmethod
    async def open(cls, kms: KmsApi, key_id: str, store: EnvelopeKeyStore) -> tuple["KmsKeyVault", CellKeys]:
        keys = await load_cell_keys(kms, key_id, store)
        return cls(kms, key_id, store, keys), keys

    async def encrypt(self, space_id: UUID, plaintext: bytes, aad: bytes) -> tuple[bytes, int]:
        version, dek = await self._current(space_id)
        nonce = os.urandom(NONCE_BYTES)
        return nonce + AESGCM(dek).encrypt(nonce, plaintext, aad), version

    async def decrypt(self, space_id: UUID, ciphertext: bytes, aad: bytes, dek_version: int) -> bytes:
        dek = await self._dek(space_id, dek_version)
        return AESGCM(dek).decrypt(ciphertext[:NONCE_BYTES], ciphertext[NONCE_BYTES:], aad)

    async def hmac(self, space_id: UUID, purpose: str, value: bytes) -> bytes:
        key = derived_key(self._hmac_root, space_id, purpose)
        return hmac_lib.new(key, value, "sha256").digest()

    async def key_versions(self, space_id: UUID) -> list[int]:
        return sorted(await self._store.load_wrapped(space_id))

    async def destroy_space(self, space_id: UUID) -> list[int]:
        """The wrapped keys leave the store and the unwrapped ones this process's memory: with the blobs
        gone, KMS has nothing left to unwrap, so every copy of the space's ciphertext stays sealed."""
        self._destroyed.add(space_id)
        self._deks.pop(space_id, None)
        return await self._store.destroy(space_id)

    async def rotate_space(self, space_id: UUID) -> int:
        """A new data key version for the space (5.14.1): new ciphertexts use it, old ones keep theirs."""
        async with self._locks.setdefault(space_id, asyncio.Lock()):
            self._deks.pop(space_id, None)
            keys = await self._keys(space_id)
            version = max(keys, default=0) + 1
            dek, blob, arn = await self._generate(space_context(space_id), self._key_of(space_id))
            await self._store.save(space_id, version, blob, KMS_PREFIX + arn)
            keys[version] = dek
            self._kek_ids.setdefault(space_id, {})[version] = KMS_PREFIX + arn
            return version

    async def _current(self, space_id: UUID) -> tuple[int, bytes]:
        keys = await self._keys(space_id)
        wanted = self._space_key(space_id)
        if keys and wanted and self._kek_ids[space_id].get(max(keys)) != KMS_PREFIX + wanted:
            # The contract names the customer's key: the next data key is generated under it, and the
            # older versions keep opening under the key that wrapped each of them.
            await self._rotate_to(space_id, wanted)
            keys = await self._keys(space_id)
        if not keys:
            async with self._locks.setdefault(space_id, asyncio.Lock()):
                keys = await self._keys(space_id)
                if not keys:
                    dek, blob, arn = await self._generate(space_context(space_id), self._key_of(space_id))
                    try:
                        await self._store.save(space_id, 1, blob, KMS_PREFIX + arn)
                    except Conflict:
                        # Another process created the space's first key a moment earlier: use theirs.
                        self._deks.pop(space_id, None)
                        keys = await self._keys(space_id)
                    else:
                        keys[1] = dek
                        self._kek_ids.setdefault(space_id, {})[1] = KMS_PREFIX + arn
        version = max(keys)
        return version, keys[version]

    async def _dek(self, space_id: UUID, version: int) -> bytes:
        keys = await self._keys(space_id)
        if version not in keys:
            self._deks.pop(space_id, None)  # another process may have rotated; reload once
            keys = await self._keys(space_id)
        if version not in keys:
            raise KeyError(f"unknown data key version {version}")
        return keys[version]

    async def _keys(self, space_id: UUID) -> dict[int, bytes]:
        if space_id in self._destroyed:
            raise PermissionError("the space's keys were destroyed")
        if space_id not in self._deks:
            wrapped = await self._store.load_wrapped(space_id)
            self._kek_ids[space_id] = {version: kek_id for version, (_, kek_id) in wrapped.items()}
            self._deks[space_id] = {
                version: await self._unwrap(space_id, blob, kek_id)
                for version, (blob, kek_id) in wrapped.items()
            }
        return self._deks[space_id]

    async def _unwrap(self, space_id: UUID, blob: bytes, kek_id: str) -> bytes:
        return await unwrap_with_kms(self._kms, blob, kek_id, space_context(space_id))

    def _key_of(self, space_id: UUID) -> str:
        return self._space_key(space_id) or self._key_id

    async def _rotate_to(self, space_id: UUID, key_id: str) -> None:
        async with self._locks.setdefault(space_id, asyncio.Lock()):
            self._deks.pop(space_id, None)
            keys = await self._keys(space_id)
            if keys and self._kek_ids[space_id].get(max(keys)) == KMS_PREFIX + key_id:
                return  # another caller rotated first
            dek, blob, arn = await self._generate(space_context(space_id), key_id)
            version = max(keys, default=0) + 1
            try:
                await self._store.save(space_id, version, blob, KMS_PREFIX + arn)
            except Conflict:
                self._deks.pop(space_id, None)  # another process saved this version first: use theirs
                return
            keys[version] = dek
            self._kek_ids[space_id][version] = KMS_PREFIX + arn

    async def _generate(self, context: Mapping[str, str], key_id: str) -> tuple[bytes, bytes, str]:
        try:
            answer = await self._kms.generate_data_key(
                KeyId=key_id, KeySpec="AES_256", EncryptionContext=dict(context)
            )
        except Exception as exc:
            if key_id == self._key_id:
                raise
            # The customer's key is disabled, deleted or no longer granted to this cell: the space stops
            # writing rather than fall back to a key the contract did not choose.
            raise Unavailable("the space's customer-managed key cannot be used", retry_after_s=60) from exc
        return answer["Plaintext"], answer["CiphertextBlob"], str(answer["KeyId"])


async def unwrap_with_kms(kms: KmsApi, blob: bytes, kek_id: str, context: Mapping[str, str]) -> bytes:
    # Naming the key refuses a blob made under any other key, even one this role may use.
    answer = await kms.decrypt(
        CiphertextBlob=blob, KeyId=kek_id.removeprefix(KMS_PREFIX), EncryptionContext=dict(context)
    )
    plaintext: bytes = answer["Plaintext"]
    return plaintext


async def load_cell_keys(kms: KmsApi, key_id: str, store: EnvelopeKeyStore) -> CellKeys:
    """The keyed-hash root and the secret-store key, generated by KMS on the cell's first start."""
    rows = await store.load_wrapped(CELL_KEYS)
    if set(CELL_KEY_NAMES) <= set(rows):
        roots = {
            version: await unwrap_with_kms(kms, rows[version][0], rows[version][1], cell_context(version))
            for version in CELL_KEY_NAMES
        }
        return CellKeys(roots[HMAC_ROOT_VERSION], roots[SECRETS_ROOT_VERSION])
    roots = {}
    for version in CELL_KEY_NAMES:
        answer = await kms.generate_data_key(
            KeyId=key_id, KeySpec="AES_256", EncryptionContext=cell_context(version)
        )
        try:
            await store.save(CELL_KEYS, version, answer["CiphertextBlob"], KMS_PREFIX + str(answer["KeyId"]))
            roots[version] = answer["Plaintext"]
        except Conflict:
            # Another process of the new cell wrote its roots first: everyone uses those.
            return await load_cell_keys(kms, key_id, store)
    return CellKeys(roots[HMAC_ROOT_VERSION], roots[SECRETS_ROOT_VERSION])


@asynccontextmanager
async def open_kms(region: str, endpoint_url: str | None = None) -> AsyncIterator[KmsApi]:
    """A KMS client signed by the default credential chain: the node's role in a managed cell."""
    config = AioConfig(connect_timeout=5, read_timeout=5, retries={"max_attempts": 5, "mode": "standard"})
    async with get_session().create_client(
        "kms", region_name=region, endpoint_url=endpoint_url, config=config
    ) as client:
        yield client
